import { chromium } from 'playwright-core';
import fs from 'node:fs';
import validator from 'gltf-validator';

const URL = process.env.URL || 'http://localhost:5199/';
fs.mkdirSync('e2e/out/wheels', { recursive: true });
let failed = 0;
const ok = (c, m) => { if (!c) failed++; console.log(c ? '  ok  ' : '  FAIL', m); };
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto(URL);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForSelector('#btn-create');
await page.uncheck('#proj-guide'); await page.click('#btn-create');
const D = () => page.evaluate(() => JSON.parse(JSON.stringify(window.__app.store.doc)));
await page.click('#btn-assets');
await page.click('.acard[data-asset="car"] [data-act="add"]');
await page.waitForTimeout(800);

console.log('# four wheel groups, each with a spin');
let d = await D();
const wheels = d.objects.filter((o) => /^Wheel (Front|Rear) (Left|Right)$/.test(o.name));
ok(wheels.length === 4 && wheels.every((w) => w.kind === 'group' && w.spin?.axis === 0), `4 wheel groups: ${wheels.map((w) => w.name).join(', ')}`);
ok(wheels.every((w) => d.objects.filter((o) => o.parent === w.id).length === 4), 'each holds the tire, rim, inner disc and hubcap');

console.log('# select a wheel: Pivot and Spin in the panel');
const fl = wheels.find((w) => w.name === 'Wheel Front Left');
await page.evaluate((id) => window.__app.store.select([id]), fl.id);
await page.waitForSelector('#pivot-center');
ok(/Pivot at/.test(await page.textContent('#pivot-readout')), 'the pivot readout shows where it is');
ok(await page.evaluate(() => document.getElementById('spin-x').classList.contains('on')), 'Spin is on, around X');
ok((await page.inputValue('#spin-speed')) === '1', 'one turn per second');

console.log('# the orange pivot marker, and dragging it');
const marker = await page.evaluate(() => { const v = window.__app.vp; const m = v.pivotMarker; return { vis: m.visible, p: m.position.toArray() }; });
ok(marker.vis, 'the pivot marker is shown for the selected group');
const childBox = (id) => page.evaluate((id) => { const b = window.__app.store.worldBounds([id]); return [b.min.x, b.min.y, b.min.z, b.max.x, b.max.y, b.max.z]; }, id);
const boxBefore = await childBox(fl.id);
const screen = await page.evaluate(() => { const { vp } = window.__app; const p = vp.pivotMarker.position.clone().project(vp.camera); const r = vp.renderer.domElement.getBoundingClientRect(); return { x: r.left + (p.x + 1) / 2 * r.width, y: r.top + (1 - p.y) / 2 * r.height }; });
const pv0 = await page.evaluate((id) => window.__app.store.pivotOf(id), fl.id);
await page.mouse.move(screen.x, screen.y); await page.mouse.down();
await page.mouse.move(screen.x + 30, screen.y - 20, { steps: 6 }); await page.mouse.up();
await page.waitForTimeout(200);
const pv1 = await page.evaluate((id) => window.__app.store.pivotOf(id), fl.id);
ok(Math.hypot(pv1[0] - pv0[0], pv1[1] - pv0[1], pv1[2] - pv0[2]) > 0.02, `dragging the marker moved the pivot (${pv0.map((v) => v.toFixed(2))} → ${pv1.map((v) => v.toFixed(2))})`);
const boxAfter = await childBox(fl.id);
ok(boxBefore.every((v, i) => Math.abs(v - boxAfter[i]) < 1e-3), 'the wheel itself did not move');
await page.evaluate(() => window.__app.store.undo());
const pv2 = await page.evaluate((id) => window.__app.store.pivotOf(id), fl.id);
ok(Math.hypot(pv2[0] - pv0[0], pv2[1] - pv0[1], pv2[2] - pv0[2]) < 1e-3, 'undo puts the pivot back on the axle');

console.log('# a wheel turned around X stays on its axle');
const tire = d.objects.find((o) => o.parent === fl.id && o.name.includes('Tire'));
const tireCentre = () => page.evaluate((id) => { const b = window.__app.store.worldBounds([id]); return [(b.min.x + b.max.x) / 2, (b.min.y + b.max.y) / 2, (b.min.z + b.max.z) / 2]; }, tire.id);
const c0 = await tireCentre();
await page.evaluate((id) => window.__app.store.update(id, { rotation: [137, 0, 0] }), fl.id);
const c1 = await tireCentre();
ok(c0.every((v, i) => Math.abs(v - c1[i]) < 1e-3), 'turning the group by 137° leaves the tire centre where it is: it spins on the axle');
await page.evaluate((id) => window.__app.store.update(id, { rotation: [0, 0, 0] }), fl.id);

console.log('# Preview: the wheels really turn');
await page.evaluate(() => window.__app.store.select([]));
await page.click('#btn-preview');
await page.waitForTimeout(300);
const angle = () => page.evaluate((id) => { const n = window.__app.vp.nodes.get(id); return n.quaternion.toArray(); }, fl.id);
const q0 = await angle();
await page.waitForTimeout(350);
const q1 = await angle();
ok(q0.some((v, i) => Math.abs(v - q1[i]) > 0.02), 'the wheel group turns over time in Preview');
const tireWorld = () => page.evaluate((id) => { const n = window.__app.vp.nodes.get(id); n.updateWorldMatrix(true, false); const v = new n.position.constructor(); n.getWorldPosition(v); return v.toArray(); }, tire.id);
const w0 = await tireWorld(); await page.waitForTimeout(200); const w1 = await tireWorld();
ok(w0.every((v, i) => Math.abs(v - w1[i]) < 1e-3), 'and the tire stays on its axle while it turns');
await page.click('#btn-preview');
await page.waitForTimeout(300);
const q2 = await angle();
ok(Math.abs(q2[0]) < 1e-6 && Math.abs(q2[3] - 1) < 1e-6, 'back in the editor the wheel is at rest again (the preview spin is not saved)');
ok((await D()).objects.find((o) => o.id === fl.id).rotation.every((v) => v === 0), 'the project data was not changed by the preview');

console.log('# export: a looping Spin animation');
await page.click('#btn-export');
await page.click('[data-tab="software"]');
await page.click('.card[data-preset="blender"]');
await page.selectOption('#export-format', 'glb');
await page.waitForFunction(() => document.querySelector('#verify')?.dataset.ok !== undefined, null, { timeout: 30000 });
ok((await page.getAttribute('#verify', 'data-ok')) === 'true', 'self-test: ' + (await page.textContent('#verify')));
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('#btn-download')]);
await dl.saveAs('e2e/out/wheels/car.glb');
const bytes = new Uint8Array(fs.readFileSync('e2e/out/wheels/car.glb'));
const rep = await validator.validateBytes(bytes);
ok(rep.issues.numErrors === 0, `glTF validator: ${rep.issues.numErrors} errors, ${rep.issues.numWarnings} warnings ${rep.issues.messages.slice(0, 3).map((m) => m.code + ' ' + m.pointer).join('; ')}`);
const dv = new DataView(bytes.buffer, bytes.byteOffset);
const gltf = JSON.parse(new TextDecoder().decode(bytes.subarray(20, 20 + dv.getUint32(12, true))));
ok(gltf.animations?.length === 1 && gltf.animations[0].name === 'Spin', `one animation called ${gltf.animations?.[0]?.name}`);
const targets = gltf.animations[0].channels.map((c) => gltf.nodes[c.target.node].name).sort();
ok(targets.join() === 'Wheel Front Left,Wheel Front Right,Wheel Rear Left,Wheel Rear Right', `it turns the 4 wheel nodes: ${targets.join(', ')}`);
ok(gltf.animations[0].channels.every((c) => c.target.path === 'rotation'), 'by rotation');
const node = gltf.nodes.find((n) => n.name === 'Wheel Front Left');
ok(Array.isArray(node.translation) && Math.abs(node.translation[1] - 0.36) < 0.02, `the node sits on the axle (height ${node.translation?.[1]?.toFixed(2)} m)`);
ok(gltf.nodes.find((n) => n.name === 'Front Tire Left') !== undefined, 'its tire is a child of it');

console.log('# spin off: nothing is animated');
await page.evaluate(() => { const s = window.__app.store; s.setSpin(s.doc.objects.filter((o) => o.spin).map((o) => o.id), null); });
await page.click('#btn-export');
await page.click('[data-tab="software"]');
await page.click('.card[data-preset="blender"]');
await page.selectOption('#export-format', 'glb');
await page.waitForFunction(() => document.querySelector('#verify')?.dataset.ok !== undefined, null, { timeout: 30000 });
const [dl2] = await Promise.all([page.waitForEvent('download'), page.click('#btn-download')]);
await dl2.saveAs('e2e/out/wheels/car-still.glb');
const b2 = new Uint8Array(fs.readFileSync('e2e/out/wheels/car-still.glb'));
const dv2 = new DataView(b2.buffer, b2.byteOffset);
const g2 = JSON.parse(new TextDecoder().decode(b2.subarray(20, 20 + dv2.getUint32(12, true))));
ok(!g2.animations?.length, 'no animation without spin');

ok(errs.length === 0, 'no console errors' + (errs.length ? ': ' + errs.slice(0, 3).join(' | ') : ''));
await browser.close();
process.exit(failed ? 1 : 0);
