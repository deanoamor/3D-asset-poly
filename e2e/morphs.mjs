import { chromium } from 'playwright-core';
import fs from 'node:fs';
import validator from 'gltf-validator';
const URL = process.env.URL || 'http://localhost:5199/';
fs.mkdirSync('e2e/out/morphs', { recursive: true });
let failed = 0;
const ok = (c, m) => { if (!c) failed++; console.log(c ? '  ok  ' : '  FAIL', m); };
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader'] });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true })).newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto(URL); await page.evaluate(() => localStorage.clear()); await page.reload();
await page.waitForSelector('#btn-create'); await page.uncheck('#proj-guide'); await page.click('#btn-create');
const D = () => page.evaluate(() => JSON.parse(JSON.stringify(window.__app.store.doc)));
const ids = await page.evaluate(() => { const s = window.__app.store; s.addShape('sphere', { name: 'Head', position: [0, 1.5, 0], size: [0.6, 0.6, 0.6] }); const m = s.addShape('box', { name: 'Mouth', position: [0, 1.4, 0.3], size: [0.2, 0.05, 0.05] }); s.addShape('box', { name: 'Body', position: [0, 0.6, 0], size: [0.6, 1, 0.35] }); return { mouth: m.id }; });
console.log('# make an expression');
await page.waitForSelector('#morph-new');
await page.click('#morph-new');
ok(await page.isVisible('#morph-draft'), 'the draft banner shows');
await page.fill('#morph-name', 'Smile');
await page.evaluate((id) => window.__app.store.update(id, { size: [0.45, 0.05, 0.05] }, false), ids.mouth);
await page.screenshot({ path: 'e2e/out/morphs/draft.png' });
await page.click('#morph-done');
let d = await D();
ok(d.morphs?.length === 1 && d.morphs[0].name === 'Smile', 'the expression "Smile" is saved');
ok(d.objects.find((o) => o.name === 'Mouth').size[0] === 0.2, 'the model is back to normal');
ok(await page.isVisible('.morph-row'), 'it is listed with a slider');
console.log('# preview with the slider');
const mouthW = () => page.evaluate(() => { let x = 0; window.__app.vp.scene.traverse((o) => { if (o.isMesh && o.name === 'Mouth') x = o.scale.x; }); return x; });
ok(Math.abs((await mouthW()) - 0.2) < 1e-6, 'at 0 the mouth is as modelled');
await page.fill('.morph-w', '100'); await page.dispatchEvent('.morph-w', 'input');
await page.waitForTimeout(300);
ok(Math.abs((await mouthW()) - 0.45) < 1e-3, `at 100 the mouth is wide: ${await mouthW()}`);
ok((await D()).objects.find((o) => o.name === 'Mouth').size[0] === 0.2, 'previewing never changes the project');
await page.screenshot({ path: 'e2e/out/morphs/preview.png' });
console.log('# survives a reload');
await page.fill('.morph-w', '0'); await page.dispatchEvent('.morph-w', 'input');
await page.waitForTimeout(1500);
await page.reload(); await page.waitForSelector('.morph-row', { timeout: 5000 }).catch(() => {});
ok((await D()).morphs?.length === 1, 'the expression is still there after a reload');
console.log('# export');
await page.click('#btn-export'); await page.waitForSelector('#export-format'); await page.selectOption('#export-format', 'glb');
await page.waitForFunction(() => document.querySelector('#verify')?.dataset.ok === 'true' && /morph/.test(document.querySelector('#file-stats').textContent), null, { timeout: 40000 });
console.log('  ', (await page.textContent('#file-stats')).trim());
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('#btn-download')]);
const st = await dl.createReadStream(); const c = []; for await (const x of st) c.push(x);
const bytes = new Uint8Array(Buffer.concat(c));
const dv = new DataView(bytes.buffer, bytes.byteOffset);
const json = JSON.parse(new TextDecoder().decode(bytes.subarray(20, 20 + dv.getUint32(12, true))));
const rep = await validator.validateBytes(bytes);
ok(rep.issues.numErrors === 0, `validator: ${rep.issues.numErrors} errors ${rep.issues.messages.slice(0, 2).map((m) => m.code)}`);
ok(json.meshes.some((m) => m.extras?.targetNames?.includes('Smile')), 'the file has a morph target called Smile');
console.log('# delete');
await page.waitForSelector('.morph-del');
await page.click('.morph-del');
ok(!(await D()).morphs, 'Delete removes it');
ok(errs.length === 0, 'no console errors' + (errs[0] ? ': ' + errs[0] : ''));
await browser.close();
process.exit(failed ? 1 : 0);
