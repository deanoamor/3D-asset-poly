import { chromium } from 'playwright-core';
import fs from 'node:fs';
import validator from 'gltf-validator';

const URL = process.env.URL || 'http://localhost:5199/';
fs.mkdirSync('e2e/out/rig', { recursive: true });
let failed = 0;
const ok = (c, m) => { if (!c) failed++; console.log(c ? '  ok  ' : '  FAIL', m); };
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto(URL);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForSelector('#btn-create');
await page.uncheck('#proj-guide'); await page.click('#btn-create');
const D = () => page.evaluate(() => JSON.parse(JSON.stringify(window.__app.store.doc)));

console.log('# a character comes with a skeleton');
await page.click('#btn-assets');
await page.click('.acard[data-asset="police"] [data-act="add"]');
await page.waitForTimeout(600);
let d = await D();
ok(d.rig?.length === 22, `police has ${d.rig?.length} joints`);
const group = d.objects.find((o) => o.kind === 'group');
ok(d.rig.every((j) => j.owner === group.id), 'the joints belong to the character group');
ok((await page.textContent('.skel-count')).includes('22'), 'the Skeleton section lists them');
ok((await page.$$('#joint-list .jrowitem')).length === 22, 'one row per joint');
ok((await page.textContent('#joint-list')).includes('Knee Left'), 'joints have clear names');

console.log('# props have none, and "Add person skeleton" works on any figure');
await page.click('#btn-assets');
await page.click('.acard[data-asset="car"] [data-act="add"]');
await page.waitForTimeout(500);
d = await D();
ok(d.rig.length === 22, 'adding a car adds no joints');
await page.evaluate(() => window.__app.store.select([window.__app.store.doc.objects.find((o) => o.name === 'Car').id]));

console.log('# click a joint in the list, edit it');
await page.click('#joint-list .jrowitem >> text=Elbow Left');
await page.waitForSelector('#joint-editor');
ok((await page.inputValue('#joint-name')) === 'Elbow Left', 'the editor shows the joint');
await page.fill('#joint-name', 'Left Elbow'); await page.press('#joint-name', 'Enter');
await page.waitForFunction(() => window.__app.store.doc.rig.some((j) => j.name === 'Left Elbow'));
ok(true, 'renaming works');
const before = (await D()).rig.find((j) => j.name === 'Left Elbow').pos;
await page.fill('.jrow label:nth-child(2) input', String(before[1] - 0.1)); await page.press('.jrow label:nth-child(2) input', 'Enter');
await page.waitForFunction((y) => Math.abs(window.__app.store.doc.rig.find((j) => j.name === 'Left Elbow').pos[1] - y) < 1e-6, before[1] - 0.1);
ok(true, 'typing a Y value moves the joint');
await page.evaluate(() => window.__app.store.undo());
ok(Math.abs((await D()).rig.find((j) => j.name === 'Left Elbow').pos[1] - before[1]) < 1e-6, 'undo puts it back');

console.log('# drag a joint in the scene');
await page.evaluate(() => { const s = window.__app.store; s.select([]); window.__app.vp.focus(); });
await page.waitForTimeout(600);
const screen = (name) => page.evaluate((n) => {
  const { store, vp } = window.__app;
  const j = store.doc.rig.find((q) => q.name === n);
  const v = { x: j.pos[0], y: j.pos[1], z: j.pos[2] };
  const cam = vp.camera;
  const p = new (cam.position.constructor)(v.x, v.y, v.z).project(cam);
  const r = vp.renderer.domElement.getBoundingClientRect();
  return { x: r.left + ((p.x + 1) / 2) * r.width, y: r.top + ((1 - p.y) / 2) * r.height };
}, name);
const wrist = await screen('Wrist Right');
const w0 = (await D()).rig.find((j) => j.name === 'Wrist Right').pos;
await page.mouse.move(wrist.x, wrist.y); await page.mouse.down();
await page.mouse.move(wrist.x + 40, wrist.y + 10, { steps: 6 }); await page.mouse.up();
await page.waitForTimeout(200);
const w1 = (await D()).rig.find((j) => j.name === 'Wrist Right').pos;
ok(Math.hypot(w1[0] - w0[0], w1[1] - w0[1], w1[2] - w0[2]) > 0.02, `dragging the wrist ball moved it (${w0.map((v) => v.toFixed(2))} → ${w1.map((v) => v.toFixed(2))})`);
ok((await page.evaluate(() => window.__app.store.joint(window.__app.store.selectedJoint)?.name)) === 'Wrist Right', 'and picked it');
await page.evaluate(() => window.__app.store.undo());

console.log('# the skeleton follows the character when it is moved');
const hipsBefore = (await D()).rig.find((j) => j.name === 'Hips').pos;
await page.evaluate(() => { const s = window.__app.store; const g = s.doc.objects.find((o) => o.name === 'Police Officer'); s.update(g.id, { position: [g.position[0] + 1, g.position[1], g.position[2] + 2] }); });
const hipsAfter = (await D()).rig.find((j) => j.name === 'Hips').pos;
ok(Math.abs(hipsAfter[0] - hipsBefore[0] - 1) < 1e-3 && Math.abs(hipsAfter[2] - hipsBefore[2] - 2) < 1e-3, 'moving the character moves its joints too');
await page.evaluate(() => window.__app.store.undo());

console.log('# hide and show');
await page.click('#btn-rig-show');
ok(!(await page.evaluate(() => window.__app.store.ui.showRig)), 'the skeleton can be hidden');
await page.click('#btn-rig-show');

console.log('# deleting the character removes its skeleton');
await page.evaluate(() => { const s = window.__app.store; const g = s.doc.objects.find((o) => o.name === 'Police Officer'); s.select([g.id]); s.deleteSelected(); });
ok(!(await D()).rig, 'no joints left');
await page.evaluate(() => window.__app.store.undo());
ok((await D()).rig?.length === 22, 'undo brings the character and its skeleton back');

console.log('# export carries the skeleton');
await page.evaluate(() => { const s = window.__app.store; s.select([]); });
await page.click('#btn-export');
await page.click('[data-tab="3d"], [data-tab="software"]');
await page.click('.card[data-preset="blender"]');
await page.selectOption('#export-format', 'glb');
await page.waitForFunction(() => document.querySelector('#verify')?.dataset.ok !== undefined, null, { timeout: 30000 });
ok((await page.getAttribute('#verify', 'data-ok')) === 'true', 'self-test: ' + (await page.textContent('#verify')));
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('#btn-download')]);
const file = 'e2e/out/rig/police.glb';
await dl.saveAs(file);
const bytes = new Uint8Array(fs.readFileSync(file));
const r = await validator.validateBytes(bytes);
ok(r.issues.numErrors === 0, `glTF validator: ${r.issues.numErrors} errors, ${r.issues.numWarnings} warnings ${r.issues.messages.map((m) => m.code + ' ' + m.pointer).join('; ')}`);
const dv = new DataView(bytes.buffer, bytes.byteOffset);
const gltf = JSON.parse(new TextDecoder().decode(bytes.subarray(20, 20 + dv.getUint32(12, true))));
ok(gltf.skins?.length === 1, `one skin (${gltf.skins?.length})`);
const skinNodes = gltf.nodes.filter((n) => n.skin !== undefined);
ok(gltf.skins[0].joints.length === 22, `${gltf.skins[0].joints.length} joints in the skin`);
const jointNames = gltf.skins[0].joints.map((i) => gltf.nodes[i].name);
ok(['Hips', 'Knee Left', 'Left Elbow', 'Head', 'Toe Right'].every((n) => jointNames.includes(n)), 'joint names survive');
ok(skinNodes.length === 1 && skinNodes[0].name === 'Police Officer', `one skinned mesh for the character: ${skinNodes.map((n) => n.name)}`);
ok(gltf.meshes[skinNodes[0].mesh].primitives.length > 5, `with ${gltf.meshes[skinNodes[0].mesh].primitives.length} materials`);
ok(gltf.nodes.some((n) => n.mesh !== undefined && n.skin === undefined), 'the car is exported as ordinary meshes, with no skin');
ok(gltf.meshes[skinNodes[0].mesh].primitives.every((p) => p.attributes.JOINTS_0 !== undefined && p.attributes.WEIGHTS_0 !== undefined), 'every primitive has JOINTS_0 and WEIGHTS_0');
ok(gltf.nodes.some((n) => /Armature/.test(n.name || '')), 'there is an Armature node');
ok(gltf.skins[0].inverseBindMatrices !== undefined, 'inverse bind matrices are stored');

ok(errs.length === 0, 'no console errors' + (errs.length ? ': ' + errs.slice(0, 3).join(' | ') : ''));
await browser.close();
process.exit(failed ? 1 : 0);
