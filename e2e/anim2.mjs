import { chromium } from 'playwright-core';
import validator from 'gltf-validator';
const URL = process.env.URL || 'http://localhost:5199/';
let failed = 0;
const ok = (c, m) => { if (!c) failed++; console.log(c ? '  ok  ' : '  FAIL', m); };
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto(URL);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForSelector('#btn-create');
await page.uncheck('#proj-guide'); await page.click('#btn-create');
await page.click('#btn-assets');
await page.click('.acard[data-asset="soldier"] [data-act="add"]');
await page.waitForTimeout(800);
console.log('# new ready-made animations');
const opts = await page.$$eval('#anim-preset option', (o) => o.map((x) => x.textContent.split(' · ')[0]));
for (const n of ['Jump', 'Attack', 'Hit', 'Death', 'Crouch', 'Strafe']) ok(opts.includes(n), `${n} is offered`);
for (const n of ['jump', 'attack', 'hit', 'death', 'crouch', 'strafe']) { await page.selectOption('#anim-preset', n); await page.waitForTimeout(100); await page.click('#anim-play').catch(() => {}); }
const names = await page.evaluate(() => window.__app.store.doc.anims.map((c) => c.name));
ok(names.join() === 'Jump,Attack,Hit,Death,Crouch,Strafe', `clips: ${names}`);
console.log('# root motion moves the character in the viewport');
await page.selectOption('#anim-clip', await page.evaluate(() => window.__app.store.doc.anims[0].id));
const hipsY = () => page.evaluate(() => { let y = null; window.__app.vp.scene.traverse((o) => { if (o.isBone && o.name === 'Hips' && y === null) y = o.position.y; }); return y; });
await page.evaluate(() => window.__app.store.setAnimPlaying(false));
await page.fill('#anim-time', '0'); await page.dispatchEvent('#anim-time', 'input'); await page.waitForTimeout(200);
const y0 = await hipsY();
await page.fill('#anim-time', '0.55'); await page.dispatchEvent('#anim-time', 'input'); await page.waitForTimeout(200);
const y1 = await hipsY();
ok(y1 - y0 > 0.2, `the jump lifts the hips ${(y1 - y0).toFixed(2)} m`);
console.log('# easing and move fields');
await page.selectOption('#anim-ease', 'smooth');
ok((await page.evaluate(() => window.__app.store.doc.anims[0].ease)) === 'smooth', 'easing is stored');
await page.fill('#anim-time', '0.4'); await page.dispatchEvent('#anim-time', 'input');
const keyAt = await page.evaluate(() => window.__app.store.doc.anims[0].keys.findIndex((k) => Math.abs(k.t - 0.4) < 0.02));
ok(await page.isEnabled('#anim-root-z'), 'the Move fields are enabled on a key');
await page.fill('#anim-root-z', '0.5'); await page.dispatchEvent('#anim-root-z', 'change');
ok((await page.evaluate((i) => window.__app.store.doc.anims[0].keys[i].root?.[2], keyAt)) === 0.5, 'Move Z is stored on that key');
console.log('# material');
await page.evaluate(() => window.__app.store.select?.([]));
console.log('# export stats and file');
await page.click('#btn-export');
await page.waitForSelector('#file-stats');
await page.waitForFunction(() => /draw call/.test(document.querySelector('#file-stats')?.textContent || ''), null, { timeout: 30000 });
const stat = await page.textContent('#file-stats');
ok(/KB|MB/.test(stat) && /draw call/.test(stat) && /material/.test(stat), `stats: ${stat.trim()}`);
await page.waitForFunction(() => document.querySelector('#verify')?.dataset.ok === 'true', null, { timeout: 30000 });
ok(true, 'file verified');
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('#btn-download')]);
const buf = await (async () => { const s = await dl.createReadStream(); const c = []; for await (const x of s) c.push(x); return Buffer.concat(c); })();
const rep = await validator.validateBytes(new Uint8Array(buf));
ok(rep.issues.numErrors === 0, `validator: ${rep.issues.numErrors} errors ${rep.issues.numWarnings} warnings`);
ok(errs.length === 0, 'no console errors' + (errs.length ? ': ' + errs[0] : ''));
await browser.close();
process.exit(failed ? 1 : 0);
