import { chromium } from 'playwright-core';
import fs from 'node:fs';
import validator from 'gltf-validator';
const URL = process.env.URL || 'http://localhost:5199/';
fs.mkdirSync('e2e/out/textures', { recursive: true });
let failed = 0;
const ok = (c, m) => { if (!c) failed++; console.log(c ? '  ok  ' : '  FAIL', m); };
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader'] });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true })).newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto(URL); await page.evaluate(() => localStorage.clear()); await page.reload();
await page.waitForSelector('#btn-create'); await page.uncheck('#proj-guide'); await page.click('#btn-create');
const D = () => page.evaluate(() => JSON.parse(JSON.stringify(window.__app.store.doc)));
await page.evaluate(() => { const s = window.__app.store; const a = s.addShape('sphere', { name: 'Head', position: [0, 1.2, 0], size: [0.6, 0.6, 0.6] }); s.update(a.id, { color: '#e8b894' }); s.addShape('box', { name: 'Body', position: [0, 0.5, 0], size: [0.6, 0.9, 0.35] }); s.select([a.id]); });
await page.waitForSelector('#pic-builtin');
console.log('# a picture on a shape');
await page.selectOption('#pic-builtin', 'face');
await page.waitForTimeout(800);
let d = await D();
ok(d.pictures?.length === 1 && d.objects.find((o) => o.name === 'Head').tex?.id === d.pictures[0].id, 'the Face picture is stored and worn by the head');
const mapped = () => page.evaluate(() => { let r = null; window.__app.vp.scene.traverse((o) => { if (o.isMesh && o.name === 'Head') r = { map: !!o.material.map, uv: !!o.geometry.getAttribute('uv') }; }); return r; });
const mp = await mapped();
ok(mp?.map && mp.uv, 'the viewport shows it (material map + UV)');
await page.screenshot({ path: 'e2e/out/textures/viewport.png', clip: { x: 250, y: 48, width: 920, height: 700 } });
await page.click('#pic-front');
ok((await D()).objects.find((o) => o.name === 'Head').tex.mode === 'front', 'Front only is stored');
console.log('# export with an atlas');
const exportGlb = async (atlas) => {
  await page.click('#btn-export'); await page.waitForSelector('#export-format'); await page.selectOption('#export-format', 'glb');
  if (atlas) await page.check('#export-atlas'); else await page.uncheck('#export-atlas');
  await page.waitForFunction(() => document.querySelector('#verify')?.dataset.ok === 'true' && /draw call/.test(document.querySelector('#file-stats').textContent), null, { timeout: 40000 });
  const stat = await page.textContent('#file-stats');
  const [dl] = await Promise.all([page.waitForEvent('download'), page.click('#btn-download')]);
  const s = await dl.createReadStream(); const c = []; for await (const x of s) c.push(x);
  const bytes = new Uint8Array(Buffer.concat(c));
  const dv = new DataView(bytes.buffer, bytes.byteOffset);
  const json = JSON.parse(new TextDecoder().decode(bytes.subarray(20, 20 + dv.getUint32(12, true))));
  const rep = await validator.validateBytes(bytes);
  return { stat, json, rep };
};
const a = await exportGlb(true);
console.log('  ', a.stat.trim());
ok(a.rep.issues.numErrors === 0, `validator: ${a.rep.issues.numErrors} errors ${a.rep.issues.messages.slice(0, 2).map((m) => m.code)}`);
ok(a.json.materials?.length === 1 && a.json.images?.length === 1, `ONE material and one image (${a.json.materials?.length} / ${a.json.images?.length})`);
ok(a.json.meshes.every((m) => m.primitives.every((p) => p.attributes.TEXCOORD_0 !== undefined)), 'every mesh has UVs');
ok(a.json.meshes.length === 2 || a.json.meshes.length === 1, 'meshes: ' + a.json.meshes.length);
console.log('# export without an atlas');
const b = await exportGlb(false);
ok(b.rep.issues.numErrors === 0, `validator: ${b.rep.issues.numErrors} errors`);
ok(b.json.materials.length === 2 && b.json.images?.length === 1, `plain colour for the body, a picture material for the head (${b.json.materials.length} materials)`);
console.log('# on a character with a skeleton');
await page.evaluate(() => { localStorage.clear(); });
await page.reload(); await page.waitForSelector('#btn-create'); await page.uncheck('#proj-guide'); await page.click('#btn-create');
await page.click('#btn-assets'); await page.click('.acard[data-asset="soldier"] [data-act="add"]'); await page.waitForTimeout(800);
await page.evaluate(() => { const s = window.__app.store; const o = s.doc.objects.find((x) => x.kind === 'shape' && /head/i.test(x.name)) ?? s.doc.objects.find((x) => x.kind === 'shape'); s.select([o.id]); });
await page.waitForSelector('#pic-builtin'); await page.selectOption('#pic-builtin', 'star'); await page.waitForTimeout(600);
const c = await exportGlb(true);
console.log('  ', c.stat.trim());
ok(c.rep.issues.numErrors === 0, `validator: ${c.rep.issues.numErrors} errors ${c.rep.issues.messages.slice(0, 2).map((m) => m.code + ' ' + m.pointer)}`);
ok(c.json.skins?.length === 1 && c.json.materials.length === 1 && c.json.images?.length === 1, `one skin, ${c.json.materials.length} material(s), ${c.json.images?.length} image(s)`);
ok(c.json.meshes[0].primitives.every((p) => p.attributes.TEXCOORD_0 !== undefined && p.attributes.JOINTS_0 !== undefined), 'the skinned mesh has UVs and joints');
ok(errs.length === 0, 'no console errors' + (errs[0] ? ': ' + errs[0] : ''));
await browser.close();
process.exit(failed ? 1 : 0);
