import { chromium } from 'playwright-core';
import fs from 'node:fs';
import validator from 'gltf-validator';

const URL = process.env.URL || 'http://localhost:5199/';
fs.mkdirSync('e2e/out/animation', { recursive: true });
let failed = 0;
const ok = (c, m) => { if (!c) failed++; console.log(c ? '  ok  ' : '  FAIL', m); };
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 }, acceptDownloads: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto(URL);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForSelector('#btn-create');
await page.uncheck('#proj-guide'); await page.click('#btn-create');
const D = () => page.evaluate(() => JSON.parse(JSON.stringify(window.__app.store.doc)));
const bone = (name) => page.evaluate((n) => { let q = null; window.__app.vp.scene.traverse((o) => { if (o.isBone && o.name === n && !q) q = o.quaternion.toArray(); }); return q; }, name);
await page.click('#btn-assets');
await page.click('.acard[data-asset="police"] [data-act="add"]');
await page.waitForTimeout(800);

console.log('# the Animation section');
ok(await page.isVisible('#animation'), 'a character with a skeleton shows the Animation section');
ok((await page.textContent('#anim-clip')).includes('No animations yet'), 'it starts with no clips');
ok(!(await page.isVisible('#anim-play')), 'no player until there is a clip');

console.log('# a ready-made Walk');
await page.selectOption('#anim-preset', 'walk');
await page.waitForSelector('#anim-play');
let d = await D();
ok(d.anims?.length === 1 && d.anims[0].name === 'Walk' && d.anims[0].keys.length === 8, 'Walk was added: 8 keys');
ok(await page.evaluate(() => window.__app.store.animPlaying), 'it starts playing');
await page.waitForTimeout(500);
ok((await page.textContent('#anim-play')).includes('Pause'), 'the button now says Pause');
const k0 = await bone('Knee Left');
await page.waitForTimeout(300);
const k1 = await bone('Knee Left');
ok(!!k0 && !!k1 && k0.some((v, i) => Math.abs(v - k1[i]) > 0.01), 'the knee bone is turning while it plays');
const hip0 = await bone('Hip Left'); await page.waitForTimeout(250); const hip1 = await bone('Hip Left');
ok(hip0.some((v, i) => Math.abs(v - hip1[i]) > 0.01), 'and so is the hip');
ok(!(await page.evaluate(() => !!window.__app.store.doc.pose)), 'playing never changes the saved pose');

console.log('# bottom timeline can be hidden');
const bx = await page.evaluate(() => { const r = document.querySelector('#animation').getBoundingClientRect(); const v = document.querySelector('#stage').getBoundingClientRect(); return { top: r.top, w: r.width, vw: v.width, vb: v.bottom }; });
ok(bx.top >= bx.vb - 1 && bx.w > 600, `timeline sits under the viewport, ${Math.round(bx.w)}px wide`);
await page.screenshot({ path: 'e2e/out/animation/timeline.png' });
await page.click('#anim-toggle');
ok(!(await page.isVisible('#anim-play')) && await page.isVisible('#anim-toggle'), 'hiding leaves only the Animation tab');
await page.click('#anim-toggle');
ok(await page.isVisible('#anim-play'), 'showing brings the timeline back');

console.log('# pause and scrub');
await page.click('#anim-play');
ok(!(await page.evaluate(() => window.__app.store.animPlaying)), 'Pause stops it');
await page.fill('#anim-time', '0.25');
await page.dispatchEvent('#anim-time', 'input');
await page.waitForTimeout(200);
ok((await page.textContent('#anim-readout')).startsWith('0.25'), `the readout follows the slider: ${await page.textContent('#anim-readout')}`);
const quarter = await bone('Hip Left');
await page.fill('#anim-time', '0.75');
await page.dispatchEvent('#anim-time', 'input');
await page.waitForTimeout(200);
const three = await bone('Hip Left');
ok(quarter.some((v, i) => Math.abs(v - three[i]) > 0.1), 'scrubbing to another time shows another pose (the leg is on the other side)');
ok((await page.$$('#anim-keys .akey')).length === 8, 'the timeline shows 8 key markers');

console.log('# Preview plays the clip too');
await page.click('#anim-play');
await page.evaluate(() => window.__app.store.select([]));
await page.click('#btn-preview');
await page.waitForTimeout(400);
ok(!(await page.evaluate(() => window.__app.vp.model.visible)), 'in Preview the animated character is shown');
const p0 = await bone('Knee Right'); await page.waitForTimeout(250); const p1 = await bone('Knee Right');
ok(p0.some((v, i) => Math.abs(v - p1[i]) > 0.01), 'and it moves');
await page.click('#btn-preview');
await page.click('#anim-play');

console.log('# your own animation from keys');
await page.click('#anim-new');
await page.waitForSelector('#anim-name');
d = await D();
ok(d.anims.length === 2, 'a new clip was added');
const mine = d.anims[1];
ok(mine.keys.length === 1 && mine.keys[0].t === 0, 'it starts with one key (the current pose)');
await page.fill('#anim-time', '0.5'); await page.dispatchEvent('#anim-time', 'input');
await page.waitForTimeout(150);
await page.click('#anim-key-add'); // while looking at the clip this only explains what to do
ok((await D()).anims[1].keys.length === 1, 'Key here asks you to press Edit pose here first');
await page.click('#anim-load');
await page.click('#joint-list .jrowitem >> text=Elbow Left');
await page.evaluate(() => { const s = window.__app.store; s.setJointPose(s.selectedJoint, [-80, 0, 0]); });
await page.click('#anim-key-add');
d = await D();
ok(d.anims[1].keys.length === 2 && Math.abs(d.anims[1].keys[1].t - 0.5) < 0.02, `a key at 0.5 s was stored (${d.anims[1].keys.map((k) => k.t).join(', ')})`);
const elbowId = d.rig.find((j) => j.name === 'Elbow Left').id;
ok(d.anims[1].keys[1].pose[elbowId]?.[0] === -80, 'it holds the elbow bent by 80°');
await page.fill('#anim-time', '0.25'); await page.dispatchEvent('#anim-time', 'input');
await page.waitForTimeout(150);
const half = await bone('Elbow Left');
ok(Math.abs(half[0]) > 0.15 && Math.abs(half[0]) < 0.45, `halfway between the keys the elbow is half bent (quaternion x ${half[0].toFixed(2)})`);
await page.click('#anim-play'); await page.waitForTimeout(300); await page.click('#anim-play');

console.log('# edit a key, delete a key');
await page.click('#anim-keys .akey >> nth=1');
await page.click('#anim-load');
ok(await page.evaluate(() => window.__app.store.ui.pose && !window.__app.store.animView), 'Edit pose here brings the key pose into Pose mode');
ok((await D()).pose?.[elbowId]?.[0] === -80, 'the editable pose is the key pose');
await page.evaluate(() => { const s = window.__app.store; s.selectJoint(s.doc.rig.find((j) => j.name === 'Elbow Left').id); s.setJointPose(s.selectedJoint, [-30, 0, 0]); });
await page.click('#anim-key-add');
ok((await D()).anims[1].keys[1].pose[elbowId][0] === -30, 'Key here replaced that key with the new pose');
await page.click('#anim-keys .akey >> nth=1');
await page.click('#anim-key-del');
ok((await D()).anims[1].keys.length === 1, 'Delete key removed it');

console.log('# length and loop');
await page.fill('#anim-duration', '2'); await page.press('#anim-duration', 'Enter');
await page.waitForFunction(() => window.__app.store.doc.anims[1].duration === 2);
await page.uncheck('#anim-loop');
ok((await D()).anims[1].loop === false, 'Loop can be switched off');
await page.fill('#anim-name', 'Raise arm'); await page.press('#anim-name', 'Enter');
await page.waitForFunction(() => window.__app.store.doc.anims[1].name === 'Raise arm');
ok(true, 'the clip can be renamed');

console.log('# animations are saved with the project');
await page.click('#btn-saves'); await page.click('#btn-save-now'); await page.waitForSelector('.scard');
await page.click('.modal [aria-label="Close"]');
await page.reload();
await page.waitForSelector('#animation');
ok((await D()).anims?.length === 2, 'after a reload both clips are still there');

console.log('# export: the clips are in the file');
await page.evaluate(() => { const s = window.__app.store; s.resetPose(); s.setUi({ pose: false }); s.select([]); });
await page.click('#btn-export');
await page.click('[data-tab="software"]');
await page.click('.card[data-preset="blender"]');
await page.selectOption('#export-format', 'glb');
await page.waitForSelector('#export-animations');
ok((await page.textContent('#export-animations ~ span')).includes('Walk'), 'the export offers to include the animations and names them');
await page.waitForFunction(() => document.querySelector('#verify')?.dataset.ok !== undefined, null, { timeout: 30000 });
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('#btn-download')]);
await dl.saveAs('e2e/out/animation/police.glb');
const bytes = new Uint8Array(fs.readFileSync('e2e/out/animation/police.glb'));
const rep = await validator.validateBytes(bytes);
ok(rep.issues.numErrors === 0, `glTF validator: ${rep.issues.numErrors} errors, ${rep.issues.numWarnings} warnings ${rep.issues.messages.slice(0, 3).map((m) => m.code + ' ' + m.pointer).join('; ')}`);
const dv = new DataView(bytes.buffer, bytes.byteOffset);
const gltf = JSON.parse(new TextDecoder().decode(bytes.subarray(20, 20 + dv.getUint32(12, true))));
const names = (gltf.animations ?? []).map((a) => a.name).sort();
ok(names.join() === 'Raise arm,Walk', `the animations in the file: ${names.join(', ')}`);
const walk = gltf.animations.find((a) => a.name === 'Walk');
ok(walk.channels.filter((c) => c.target.path === 'rotation').length === 22 && walk.channels.filter((c) => c.target.path === 'translation').length === 1, 'Walk turns all 22 bones and bobs the hips');
const targetNames = new Set(walk.channels.map((c) => gltf.nodes[c.target.node].name));
ok(['Hips', 'Knee Left', 'Knee Right', 'Elbow Left', 'Shoulder Right'].every((n) => targetNames.has(n)), 'the bones keep their names');
ok(gltf.skins?.length === 1 && gltf.skins[0].joints.length === 22, 'one skin with the same 22 joints');

console.log('# animations off');
await page.click('#btn-export');
await page.click('[data-tab="software"]');
await page.click('.card[data-preset="blender"]');
await page.selectOption('#export-format', 'glb');
await page.waitForSelector('#export-animations');
await page.uncheck('#export-animations');
await page.waitForTimeout(500);
await page.waitForFunction(() => document.querySelector('#verify')?.dataset.ok !== undefined, null, { timeout: 30000 });
const [dl2] = await Promise.all([page.waitForEvent('download'), page.click('#btn-download')]);
await dl2.saveAs('e2e/out/animation/still.glb');
const b2 = new Uint8Array(fs.readFileSync('e2e/out/animation/still.glb'));
const dv2 = new DataView(b2.buffer, b2.byteOffset);
const g2 = JSON.parse(new TextDecoder().decode(b2.subarray(20, 20 + dv2.getUint32(12, true))));
ok(!g2.animations?.length, 'unchecking removes the clips from the file');

console.log('# duplicating the character copies the clips');
await page.evaluate(() => { const s = window.__app.store; const g = s.doc.objects.find((o) => o.name === 'Police Officer'); s.select([g.id]); });
await page.click('#btn-duplicate');
await page.waitForTimeout(400);
d = await D();
ok(d.anims.length === 4, `the copy has its own clips (${d.anims.length} in the project)`);

ok(errs.length === 0, 'no console errors' + (errs.length ? ': ' + errs.slice(0, 3).join(' | ') : ''));
await browser.close();
process.exit(failed ? 1 : 0);
