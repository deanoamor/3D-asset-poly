import { chromium } from 'playwright-core';
import fs from 'node:fs';
const URL = process.env.URL || 'http://localhost:5199/';
fs.mkdirSync('e2e/out/weights', { recursive: true });
let failed = 0;
const ok = (c, m) => { if (!c) failed++; console.log(c ? '  ok  ' : '  FAIL', m); };
const browser = await chromium.launch({ executablePath: process.env.CHROME || '/opt/pw-browsers/chromium', args: ['--use-angle=swiftshader', '--use-gl=angle', '--enable-unsafe-swiftshader'] });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
page.on('console', (m) => m.type() === 'error' && errs.push(m.text()));
await page.goto(URL); await page.evaluate(() => localStorage.clear()); await page.reload();
await page.waitForSelector('#btn-create'); await page.uncheck('#proj-guide'); await page.click('#btn-create');
await page.click('#btn-assets'); await page.click('.acard[data-asset="police"] [data-act="add"]'); await page.waitForTimeout(800);
const S = () => page.evaluate(() => window.__app.store);
console.log('# weight view');
await page.click('[data-joint]:has-text("Shoulder Left")');
await page.click('#btn-weights');
await page.waitForTimeout(600);
const heat = () => page.evaluate(() => { let n = 0, red = 0, blue = 0; window.__app.vp.scene.traverse((o) => { if (o.isSkinnedMesh && o.geometry.getAttribute('color') && o.material.isMeshBasicMaterial) { const c = o.geometry.getAttribute('color'); for (let i = 0; i < c.count; i++) { n++; if (c.getX(i) > 0.9 && c.getZ(i) < 0.2) red++; if (c.getZ(i) > 0.9 && c.getX(i) < 0.2) blue++; } } }); return { n, red, blue }; });
let h = await heat();
ok(h.n > 100 && h.red > 0 && h.blue > h.red, `the model is heat-coloured: ${h.red} red, ${h.blue} blue of ${h.n}`);
await page.screenshot({ path: 'e2e/out/weights/view.png', clip: { x: 250, y: 48, width: 920, height: 700 } });
console.log('# reach');
const redBefore = h.red;
await page.fill('#joint-reach', '200'); await page.dispatchEvent('#joint-reach', 'input'); await page.dispatchEvent('#joint-reach', 'change');
await page.waitForTimeout(600);
h = await heat();
ok(h.red + 0 >= redBefore, `more points follow it after raising Reach (${redBefore} -> ${h.red})`);
ok((await page.evaluate(() => window.__app.store.doc.rig.find((j) => j.name === 'Shoulder Left').reach)) === 2, 'Reach is stored on the joint');
console.log('# skin section');
await page.click('#btn-weights');
const part = await page.evaluate(() => { const s = window.__app.store; const o = s.doc.objects.find((x) => x.kind === 'shape' && /Helmet|Cap|Hat/i.test(x.name)) ?? s.doc.objects.find((x) => x.kind === 'shape'); s.select([o.id]); return o.id; });
await page.waitForSelector('#skin-mode');
await page.selectOption('#skin-mode', 'joint');
await page.selectOption('#skin-joint', { label: 'Head' });
const sk = await page.evaluate((id) => window.__app.store.get(id).skin, part);
ok(sk?.mode === 'joint' && !!sk.joint, 'a part can be made to follow one joint');
ok(errs.length === 0, 'no console errors' + (errs[0] ? ': ' + errs[0] : ''));
await browser.close();
process.exit(failed ? 1 : 0);
